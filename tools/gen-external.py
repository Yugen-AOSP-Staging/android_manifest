#!/usr/bin/env python3
#
# Regenerate snippets/external.xml -- the LineageOS hardware layer -- from
# LineageOS's own manifest.
#
#   ./tools/gen-external.py [lineage-branch]
#
# The list is taken from LineageOS's default.xml, not assembled by hand, so
# linkfiles, groups and per-SoC revisions are exactly what LineageOS builds
# with. Those details matter: hardware/qcom-caf/<soc>/Android.bp is a linkfile
# from hardware/qcom-caf/common, and it is the Soong namespace declaration that
# stops every SoC HAL from defining the same module names.
#
# SPDX-License-Identifier: Apache-2.0
#
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRANCH = sys.argv[1] if len(sys.argv) > 1 else "lineage-24.0"
BASE = f"https://raw.githubusercontent.com/LineageOS/android/{BRANCH}"
SOURCES = (f"{BASE}/default.xml", f"{BASE}/snippets/lineage.xml")

# Hardware-shaped paths only. LineageOS's platform forks (build/make, art,
# bionic, frameworks), its apps and its build infrastructure are excluded on
# purpose: Yugen runs the stock AOSP platform.
KEEP = (
    "device/lineage/sepolicy",
    "device/qcom/sepolicy",
    "device/qcom/sepolicy-legacy-um",
    "device/qcom/sepolicy_vndr/",
    "external/ant-wireless/hidl",
    "external/avb",
    "external/dng_sdk",
    "external/dtc",
    "external/e2fsprogs",
    "external/gptfdisk",
    "external/json-c",
    "external/mksh",
    "external/tinyalsa",
    "external/tinycompress",
    "external/v4l2_codec2",
    "external/zstd",
    "hardware/broadcom/libbt",
    "hardware/broadcom/wlan",
    "hardware/google/pixel",
    "hardware/google/pixel-sepolicy",
    "hardware/knowles/",
    "hardware/libhardware",
    "hardware/lineage/",
    "hardware/nxp/nfc",
    "hardware/nxp/secure_element",
    "hardware/qcom/",
    "hardware/qcom-caf/",
    "packages/resources/devicesettings",
    "prebuilts/extract-tools",
    "prebuilts/tools-lineage",
    "tools/extract-utils",
    "vendor/codeaurora/telephony",
    "vendor/qcom/",
)

# Projects whose Android.bp files use `export_cflags`, a property LineageOS
# added to its build/soong fork. Stock AOSP Soong rejects it at parse time, so
# these cannot be part of a default sync on a stock platform. They are tagged
# notdefault and grouped as lineage-soong; see the README.
NEEDS_LINEAGE_SOONG = (
    "hardware/qcom-caf/sm8150/display",
    "hardware/qcom-caf/sm8250/display",
    "hardware/qcom-caf/sm8350/display",
    "hardware/qcom/sm7250/display",
    "hardware/qcom/sm8150/display",
    "vendor/qcom/opensource/commonsys-intf/display",
)

HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  LineageOS hardware layer for Yugen.

  Generated by tools/gen-external.py from LineageOS's own manifest for {branch},
  then filtered to hardware-shaped projects. Do not hand-edit: change the KEEP
  list in the script and regenerate.

  Why the details survive generation:
    * linkfiles   hardware/qcom-caf/common links os_pickup_qssi.bp into every
                  hardware/qcom-caf/<soc>/Android.bp. That file is the Soong
                  namespace declaration that keeps each SoC's HALs from
                  colliding on module names. Without it a sync of several SoC
                  families fails with hundreds of "module already defined".
    * revisions   the same repository is checked out at several
                  hardware/qcom-caf/<soc>/ paths, each on its own branch.
    * groups      LineageOS's grouping is kept so devices can be selective.

  Projects tagged notdefault use `export_cflags`, which only LineageOS's
  build/soong understands. They stay out of a default sync; see the README.

  SPDX-License-Identifier: Apache-2.0
-->
"""


def keep(path: str) -> bool:
    return any(path == p or path.startswith(p) for p in KEEP)


def groups_for(path: str) -> list[str]:
    groups = []
    if any(path == p for p in NEEDS_LINEAGE_SOONG):
        groups = ["notdefault", "lineage-soong"]
    return groups


def render(project: ET.Element) -> str:
    path = project.get("path")
    attrs = [("remote", "lineage")] + [(k, v) for k, v in project.attrib.items() if k != "groups"]
    groups = [g for g in (project.get("groups") or "").split(",") if g]
    groups = sorted(set(groups + groups_for(path)))
    if groups:
        attrs.append(("groups", ",".join(groups)))

    children = [c for c in project if c.tag in ("linkfile", "copyfile")]

    head = '  <project ' + "\n           ".join(f'{k}="{v}"' for k, v in attrs)
    if not children:
        return head + " />"

    out = [head + " >"]
    for child in children:
        cattrs = " ".join(f'{k}="{v}"' for k, v in child.attrib.items())
        out.append(f"    <{child.tag} {cattrs} />")
    out.append("  </project>")
    return "\n".join(out)


def fetch(url: str) -> list[ET.Element]:
    raw = subprocess.run(["curl", "-fsSL", url], capture_output=True, text=True)
    if raw.returncode != 0:
        sys.exit(f"could not fetch {url}")
    return [p for p in ET.fromstring(raw.stdout) if p.tag == "project"]


def main() -> int:
    projects = [p for url in SOURCES for p in fetch(url)]
    lineage = [p for p in projects if p.get("name", "").startswith("LineageOS/")]
    kept = [p for p in lineage if keep(p.get("path", ""))]
    kept.sort(key=lambda p: p.get("path", ""))

    body = "\n".join(render(p) for p in kept)
    document = (
        HEADER.format(branch=BRANCH)
        + "<manifest>\n\n"
        + body
        + "\n\n</manifest>\n"
    )
    (ROOT / "snippets/external.xml").write_text(document)

    notdefault = [p.get("path") for p in kept if groups_for(p.get("path"))]
    print(f"{len(kept)} projects kept from {len(lineage)} LineageOS projects")
    print(f"notdefault (need Lineage's build/soong): {len(notdefault)}")
    for path in notdefault:
        print(f"  {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
